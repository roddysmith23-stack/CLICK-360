const restaurantContext = { console, globalThis:{} };
restaurantContext.window = restaurantContext.globalThis;
vm.runInNewContext(fs.readFileSync('p2-restaurant-domain.js', 'utf8'), restaurantContext);
const restaurant = restaurantContext.globalThis.CLICK360_P2_RESTAURANT;
assert(restaurant, 'restaurant domain exports are available');
const owner = { uid:'owner-a', roleId:'owner' };
let order = restaurant.createOrder({ businessId:'biz-a', tableId:'mesa-1', serverName:'Ana', actor:owner, now:1000 });
order = restaurant.addLine({ order, line:{ name:'Producto directo', productId:'', code:'DIRECTO', qty:2, unitPrice:5, area:'kitchen' }, actor:owner, now:1100 });
order = restaurant.addLine({ order, line:{ productId:'coffee', code:'COF', name:'Café', qty:1, unitPrice:2, area:'bar' }, actor:owner, now:1200 });
assert.equal(restaurant.orderTotal(order), 12, 'restaurant totals include direct and inventory items');
order = restaurant.splitOrder({ order, mode:'people', parts:3, actor:owner, now:1300 });
assert.equal(order.splitPlan.parts, 3, 'split bill stores number of people');
let payment = restaurant.recordPayment({ order, amount:6, method:'Efectivo', actor:owner, idempotencyKey:'pay-1', now:1400 });
assert.equal(payment.order.remaining, 6, 'partial payment leaves remaining balance');
payment = restaurant.recordPayment({ order:payment.order, amount:6, method:'Tarjeta', actor:owner, idempotencyKey:'pay-2', now:1500 });
const paid = restaurant.finalizePayment({ order:payment.order, actor:owner, now:1600 });
assert.equal(paid.status, 'paid', 'restaurant order finalizes after exact payments');
assert.throws(() => restaurant.recordPayment({ order:paid, amount:1, method:'Efectivo', actor:owner, idempotencyKey:'late' }), /order_not_editable/, 'paid orders cannot receive duplicate charges');

const logisticsContext = { console, globalThis:{} };
logisticsContext.window = logisticsContext.globalThis;
vm.runInNewContext(fs.readFileSync('p2-logistics-domain.js', 'utf8'), logisticsContext);
const logistics = logisticsContext.globalThis.CLICK360_P2_LOGISTICS;
assert(logistics, 'logistics domain exports are available');
const vehicle = logistics.createVehicle({ input:{ businessId:'biz-a', plate:'ABC-1234', name:'Camión 1' }, actor:owner, now:2000 });
let route = logistics.createRoute({ input:{ businessId:'biz-a', name:'Ruta norte', zone:'Norte', date:'2026-07-29', vehicleId:vehicle.id }, actor:owner, vehicle, now:2100 });
let sheet = logistics.createLoadSheet({ input:{ businessId:'biz-a', routeId:route.id }, route, actor:owner, now:2200 });
let products = [{ id:'water', businessId:'biz-a', code:'WAT', name:'Agua', qty:20, price:1 }];
sheet = logistics.addLoadItem({ sheet, product:products[0], qty:10, actor:owner, now:2300 });
assert.equal(sheet.items[0].total, 10, 'load sheet totals are calculated');
sheet = logistics.confirmLoadSheet({ sheet, products, actor:owner, now:2350 });
const dispatched = logistics.dispatchLoadSheet({ sheet, route, products, actor:owner, now:2360 });
sheet = dispatched.sheet;
route = dispatched.route;
products = dispatched.products;
const sale = logistics.createRouteSale({ input:{ businessId:'biz-a', routeId:route.id, loadSheetId:sheet.id, customerName:'Cliente', items:[{ productId:'water', qty:4, price:1 }], paymentType:'credit' }, route, sheet, products, actor:owner, now:2400 });
assert.equal(sale.balance, 4, 'credit route sale keeps balance');
const collection = logistics.recordCollection({ input:{ businessId:'biz-a', routeId:route.id, routeSaleId:sale.id, amount:2, method:'cash', idempotencyKey:'col-1' }, route, sale, collections:[], actor:owner, now:2500 });
assert.equal(collection.collection.amount, 2, 'route collection is recorded');
const report = logistics.logisticsReport({ businessId:'biz-a', routes:[route], routeSales:[sale], collections:[collection.collection], returns:[], settlements:[] });
assert.equal(report.sales, 4, 'logistics report scopes sales by business');
assert.equal(report.collections, 2, 'logistics report includes collections');
assert.equal(logistics.logisticsReport({ businessId:'biz-b', routes:[route], routeSales:[sale], collections:[collection.collection] }).sales, 0, 'logistics report does not cross business boundaries');

