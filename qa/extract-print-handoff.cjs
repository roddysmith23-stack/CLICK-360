'use strict';

// Extracts the EXACT current source of the real print-handoff geometry cluster straight out of
// app.js (not a reimplementation) so a browser fixture can drive the real
// Inventory -> imprimir -> plantilla -> handoffPrint chain and measure what CLICK actually hands
// to the browser's print pipeline. Companion to qa/extract-legacy-label-renderer.cjs.
//
// printingPreferences() is stubbed, not extracted: it only affects providerId/copies fallbacks,
// and executeCanonicalLabelPrint always sets copiesHandled:true and this test always passes
// providerId='system' explicitly, so its real body is provably never reached on this path — it
// depends on activeTenantContext/currentBusiness()/device identity that don't exist outside a
// full app boot. Nothing on the measured geometry path is stubbed.

const fs = require('fs');
const path = require('path');

const appPath = path.join(__dirname, '..', 'app.js');
const app = fs.readFileSync(appPath, 'utf8');

function extractFunction(name) {
  const marker = `function ${name}(`;
  const start = app.indexOf(marker);
  if (start < 0) throw new Error(`extractFunction: could not find "${marker}" in app.js`);
  let stmtStart = start;
  while (stmtStart > 0 && !/\n/.test(app[stmtStart - 1])) stmtStart -= 1;
  const parenOpen = app.indexOf('(', start);
  let parenDepth = 0;
  let parenClose = -1;
  for (let i = parenOpen; i < app.length; i += 1) {
    if (app[i] === '(') parenDepth += 1;
    else if (app[i] === ')') { parenDepth -= 1; if (parenDepth === 0) { parenClose = i; break; } }
  }
  if (parenClose < 0) throw new Error(`extractFunction: unbalanced parens for ${name}`);
  const braceOpen = app.indexOf('{', parenClose);
  if (braceOpen < 0) throw new Error(`extractFunction: no opening brace for ${name}`);
  let depth = 0;
  let i = braceOpen;
  for (; i < app.length; i += 1) {
    if (app[i] === '{') depth += 1;
    else if (app[i] === '}') { depth -= 1; if (depth === 0) break; }
  }
  if (depth !== 0) throw new Error(`extractFunction: unbalanced braces for ${name}`);
  return app.slice(stmtStart, i + 1).trim();
}

function extractBlock(startMarker, opts = {}) {
  const start = app.indexOf(startMarker);
  if (start < 0) throw new Error(`extractBlock: could not find "${startMarker}"`);
  let stmtStart = start;
  while (stmtStart > 0 && !/\n/.test(app[stmtStart - 1])) stmtStart -= 1;
  const braceOpen = app.indexOf('{', start);
  let depth = 0;
  let i = braceOpen;
  for (; i < app.length; i += 1) {
    if (app[i] === '{') depth += 1;
    else if (app[i] === '}') { depth -= 1; if (depth === 0) break; }
  }
  let end = i + 1;
  if (opts.trailingSemicolon && app[end] === ';') end += 1;
  return app.slice(stmtStart, end).trim();
}

