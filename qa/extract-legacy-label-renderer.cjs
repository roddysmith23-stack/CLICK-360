'use strict';

// Extracts the EXACT current source of the legacy label-rendering function cluster straight out
// of app.js (not a hand-copied reimplementation) so a browser fixture can execute the real
// production code against a real persisted-template shape. Run standalone to regenerate the
// bundle qa/fixtures/generated/legacy-label-renderer.bundle.js consumed by
// qa/r32-legacy-template-preview-e2e.mjs.

const fs = require('fs');
const path = require('path');

const appPath = path.join(__dirname, '..', 'app.js');
const app = fs.readFileSync(appPath, 'utf8');

function extractFunction(name) {
  const marker = `function ${name}(`;
  const start = app.indexOf(marker);
  if (start < 0) throw new Error(`extractFunction: could not find "${marker}" in app.js`);
  // Walk back to the start of the statement (covers "async function", "  function").
  let stmtStart = start;
  while (stmtStart > 0 && !/\n/.test(app[stmtStart - 1])) stmtStart -= 1;
  // Find the matching close-paren for the parameter list FIRST (params may contain default
  // object literals like `layout = {}`, whose braces must not be mistaken for the body's).
  const parenOpen = app.indexOf('(', start);
  let parenDepth = 0;
  let parenClose = -1;
  for (let i = parenOpen; i < app.length; i += 1) {
    if (app[i] === '(') parenDepth += 1;
    else if (app[i] === ')') {
      parenDepth -= 1;
      if (parenDepth === 0) { parenClose = i; break; }
    }
  }
  if (parenClose < 0) throw new Error(`extractFunction: unbalanced parens for ${name}`);
  const braceOpen = app.indexOf('{', parenClose);
  if (braceOpen < 0) throw new Error(`extractFunction: no opening brace for ${name}`);
  let depth = 0;
  let i = braceOpen;
  for (; i < app.length; i += 1) {
    if (app[i] === '{') depth += 1;
    else if (app[i] === '}') {
      depth -= 1;
      if (depth === 0) break;
    }
  }
  if (depth !== 0) throw new Error(`extractFunction: unbalanced braces for ${name}`);
  return app.slice(stmtStart, i + 1).trim();
}

function extractConst(name) {
  const marker = `const ${name} = `;
  const start = app.indexOf(marker);
  if (start < 0) throw new Error(`extractConst: could not find "${marker}" in app.js`);
  const semiIndex = app.indexOf('\n  })();', start); // matches `const QR = (() => { ... })();` shape
  if (semiIndex < 0) throw new Error(`extractConst: could not find end of ${name}`);
  return app.slice(start, semiIndex + '\n  })();'.length).trim();
}

const FUNCTIONS = [
  'productPayload',
  'safeColor',
  'normalizedLabelLayout',
  'defaultLabelLayout',
  'drawFittedText',
  'drawCanvasElement',
  'resolvedTaxLegend',
  'productTaxLegend',
  'drawLabelOnCanvas',
  'fmt',
  'labelFmt',
  'roundRect'
];

const pieces = [
  '// AUTO-GENERATED by qa/extract-legacy-label-renderer.cjs — do not hand-edit.',
  '// Exact current source of drawLabelOnCanvas() and its real dependency cluster, pulled',
  '// straight out of app.js so this fixture exercises the real production renderer.',
  "'use strict';",
  extractConst('QR'),
  ...FUNCTIONS.map(extractFunction),
  'window.__CLICK360_LEGACY_RENDERER__ = { drawLabelOnCanvas, normalizedLabelLayout, defaultLabelLayout, productPayload, labelFmt, fmt };'
];

const outDir = path.join(__dirname, 'fixtures', 'generated');
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'legacy-label-renderer.bundle.js');
fs.writeFileSync(outPath, pieces.join('\n\n') + '\n');
console.log(`Wrote ${outPath} (${FUNCTIONS.length + 1} extracted definitions, ${pieces.join('\n').length} bytes)`);
